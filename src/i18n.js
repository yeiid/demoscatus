let currentLang = localStorage.getItem("cactusnet_lang") || "es";

export function getLang() {
  return currentLang;
}

export function setLang(lang) {
  if (lang !== "es" && lang !== "way") return;
  currentLang = lang;
  localStorage.setItem("cactusnet_lang", lang);
  updateDOM();
}

export function toggleLang() {
  setLang(currentLang === "es" ? "way" : "es");
}

export function updateDOM() {
  const elements = document.querySelectorAll("[data-i18n]");
  elements.forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dictionary[currentLang] && dictionary[currentLang][key]) {
      if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
        el.placeholder = dictionary[currentLang][key];
      } else {
        el.innerText = dictionary[currentLang][key];
      }
    }
  });

  // Update active state on language switcher buttons
  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const lang = btn.getAttribute("data-lang");
    if (lang === currentLang) {
      btn.classList.add("bg-emerald-500", "text-slate-950", "font-bold");
      btn.classList.remove("text-slate-300", "hover:bg-slate-800");
    } else {
      btn.classList.remove("bg-emerald-500", "text-slate-950", "font-bold");
      btn.classList.add("text-slate-300", "hover:bg-slate-800");
    }
  });
}

// Function to render floating language widget
